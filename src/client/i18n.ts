/**
 * Text and language for the panel.
 *
 * The browser language picks the initial language; when the host locale
 * service is available, `setLanguage` is called with its id before the panel
 * registers, so the panel follows the DSH locale instead.
 */

export type Language = 'zh' | 'en'

let language: Language = ((typeof navigator !== 'undefined' && navigator.language) || 'zh')
  .toLowerCase()
  .startsWith('zh')
  ? 'zh'
  : 'en'

export function setLanguage(localeId: string | undefined | null): void {
  const id = String(localeId ?? '').toLowerCase()
  if (id !== '') language = id.startsWith('zh') ? 'zh' : 'en'
}

export function getLanguage(): Language {
  return language
}

