/**
 * The client bundle: sources are bundled by esbuild into the DSH module-loader
 * format (`dist/client.js`), with `react` left external so the browser module
 * table provides the one React the rest of the page uses.
 */
import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'

const OUT = 'dist'
const ID = '@karoy/dsh-gitlab-workbench'

await mkdir(OUT, { recursive: true })

const result = await build({
  entryPoints: ['src/client/index.ts'],
  bundle: true,
  outfile: `${OUT}/.client.cjs`,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome100'],
  external: ['react'],
  jsx: 'transform',
  jsxFactory: 'h',
  jsxFragment: 'Fragment',
  loader: { '.css': 'text' },
  logLevel: 'info',
  metafile: true,
})

const bundle = await readFile(`${OUT}/.client.cjs`, 'utf8')
const wrapped = `/* generated by build.mjs — edit src/client/** instead. */
window.__ModuleLoader__.load({
  id: '${ID}',
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${bundle}
    })(module, exports, require);
    return module.exports && module.exports.default ? module.exports.default : module.exports;
  },
});
`
await writeFile(`${OUT}/client.js`, wrapped, 'utf8')
await rm(`${OUT}/.client.cjs`)

const bytes = Buffer.byteLength(wrapped, 'utf8')
console.log(`client bundle: ${OUT}/client.js (${(bytes / 1024).toFixed(1)} KiB)`)
for (const output of Object.values(result.metafile?.outputs ?? {})) {
  if (output.entryPoint) console.log(`  entry ${output.entryPoint}`)
}
